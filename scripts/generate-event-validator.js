import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import {readFileSync,writeFileSync} from 'node:fs';
const schema=JSON.parse(readFileSync(new URL('../schemas/adapter-event.schema.json',import.meta.url)));
const ajv=new Ajv2020({strict:false,code:{source:true,esm:true}});
const code=standalone(ajv,ajv.compile(schema)).replace('require("ajv/dist/runtime/ucs2length").default','ucs2length');
writeFileSync(new URL('../src/adapters/event-validator.js',import.meta.url),'// Generated by scripts/generate-event-validator.js; no runtime code generation.\nconst ucs2length = value => [...value].length;\n'+code);
